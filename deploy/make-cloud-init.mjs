#!/usr/bin/env node
/**
 * Builds deploy/cloud-init.yaml from deploy/vm/** — run it after changing anything in deploy/vm:
 *
 *   node deploy/make-cloud-init.mjs [git@github.com:<you>/<repo>.git]
 *
 * The YAML is what you paste into "Custom data" when creating the server (Azure, Oracle, or any cloud that takes
 * cloud-init). It carries the scripts inline because the server can't read a private repo until its deploy key is
 * added; after the first deploy, the server refreshes these scripts from the repo on every deploy.
 *
 * The scripts are gzipped + base64'd (cloud-init's `gz+b64` encoding) to keep the file small: Oracle Cloud rejects
 * user data over 32,000 bytes ("Incorrectly formatted request"), and the plain-text version was ~38 KB once encoded.
 * To read what a server will run, look at deploy/vm/ (the source) rather than this file.
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const vm = path.join(here, 'vm');
const repoUrl = process.argv[2] ?? 'git@github.com:ProXteller/universe.git';

const read = (p) => fs.readFileSync(path.join(vm, p), 'utf8');
const files = [
  { path: '/etc/universe/deploy.conf', mode: '0644', content: `REPO_URL="${repoUrl}"\nBRANCH="main"\n`, plain: true },
  { path: '/etc/universe/Caddyfile.template', mode: '0644', content: read('Caddyfile.template') },
  ...fs.readdirSync(path.join(vm, 'bin')).sort().map((f) => ({ path: `/usr/local/bin/${f}`, mode: '0755', content: read(`bin/${f}`) })),
  ...fs.readdirSync(path.join(vm, 'systemd')).sort().map((f) => ({ path: `/etc/systemd/system/${f}`, mode: '0644', content: read(`systemd/${f}`) })),
  { path: '/usr/local/sbin/universe-bootstrap', mode: '0755', content: read('bootstrap.sh') },
];

const indent = (text) =>
  text
    .replace(/\n$/, '')
    .split('\n')
    .map((l) => (l.length ? `      ${l}` : ''))
    .join('\n');

/** gzip + base64, wrapped at 76 columns (cloud-init ignores the line breaks when decoding). */
const packed = (text) =>
  zlib
    .gzipSync(Buffer.from(text, 'utf8'), { level: 9 })
    .toString('base64')
    .replace(/(.{76})/g, '$1\n');

const out = [
  '#cloud-config',
  '# UniVerse server: paste this whole file into "Custom data" when you create an Ubuntu 24.04 server.',
  '# It installs everything (Node 22, Caddy for HTTPS, the app service, auto-deploy, nightly backups) and then waits',
  '# for you to add its deploy key on GitHub. Full steps: deploy/README.md. Generated by deploy/make-cloud-init.mjs.',
  'write_files:',
  ...files.flatMap((f) =>
    f.plain
      ? [`  - path: ${f.path}`, `    permissions: '${f.mode}'`, '    content: |', indent(f.content)]
      : [`  - path: ${f.path}`, `    permissions: '${f.mode}'`, '    encoding: gz+b64', '    content: |', indent(packed(f.content))],
  ),
  'runcmd:',
  '  - [/usr/local/sbin/universe-bootstrap]',
  '',
].join('\n');

const target = path.join(here, 'cloud-init.yaml');
fs.writeFileSync(target, out);
const encoded = Buffer.from(out).toString('base64').length;
console.log(`wrote ${path.relative(process.cwd(), target)} (${(out.length / 1024).toFixed(1)} KB, ${encoded} bytes base64, repo ${repoUrl})`);
if (encoded > 32000) console.warn('warning: over the 32,000-byte user-data limit of Oracle Cloud');
